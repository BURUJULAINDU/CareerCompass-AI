def base(title,sub,size=(14,9),foot=None):
    fig=plt.figure(figsize=size,facecolor=BG)
    fig.patches.append(plt.Rectangle((0,0.93),1,0.07,transform=fig.transFigure,color=NAVY,zorder=0))
    fig.text(0.02,0.962,"CareerCompass AI",color="white",fontsize=15,fontweight="bold",va="center")
    fig.text(0.98,0.962,title,color="#93c5fd",fontsize=12,ha="right",va="center")
    fig.text(0.02,0.905,sub,color=NAVY,fontsize=11,va="center")
    fig.text(0.5,0.012,foot or FOOT,color=GREY,fontsize=8.5,ha="center")
    return fig
def panel(fig,rect,title):
    ax=fig.add_axes(rect); ax.set_facecolor("white")
    for s in ax.spines.values(): s.set_color("#cbd5e1")
    ax.set_title(title,loc="left",fontsize=11,fontweight="bold",color=NAVY,pad=8)
    return ax
def chips(ax,items,color,xmax=1.0,y=0.9,dy=0.16):
    x=0.02
    for it in items:
        w=0.016*len(it)+0.04
        if x+w>xmax: x=0.02; y-=dy
        ax.add_patch(FancyBboxPatch((x,y-0.06),w,0.1,boxstyle="round,pad=0.005,rounding_size=0.03",fc=color,ec="none",transform=ax.transAxes))
        ax.text(x+w/2,y-0.01,it,ha="center",va="center",fontsize=9,color="white",transform=ax.transAxes)
        x+=w+0.015
    ax.set_xticks([]); ax.set_yticks([])
def lines(ax,items,n=6,wrap=62,fs=9):
    y=0.93
    for it in items[:n]:
        for j,l in enumerate(textwrap.wrap(it,wrap)[:2]):
            ax.text(0.02,y,("\u2022 " if j==0 else "   ")+l,fontsize=fs,color=NAVY,va="top",transform=ax.transAxes); y-=0.085
        y-=0.02
    ax.set_xticks([]); ax.set_yticks([])

